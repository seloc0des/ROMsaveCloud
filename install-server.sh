#!/bin/bash
# OSGSameCloudService — Server Installer
# Supports: Docker (recommended) or systemd service (bare-metal)
#
# Usage:
#   bash install-server.sh
#   bash install-server.sh --uninstall

set -euo pipefail

# --- Colors ---

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
DIM='\033[2m'
NC='\033[0m'

info()  { echo -e "  ${CYAN}>>>${NC} $*"; }
ok()    { echo -e "  ${GREEN} ✓ ${NC} $*"; }
warn()  { echo -e "  ${YELLOW} ! ${NC} $*"; }
err()   { echo -e "  ${RED} ✗ ${NC} $*" >&2; }

step_header() {
    local num="$1" title="$2"
    echo ""
    echo -e "  ${BOLD}Step ${num}: ${title}${NC}"
    echo -e "  ${DIM}$(printf '%.0s─' {1..44})${NC}"
}

# --- Helpers ---

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

check_python() {
    for c in python3 python; do
        if command -v "$c" &>/dev/null; then
            local ver
            ver=$("$c" -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')" 2>/dev/null) || continue
            local major minor
            major=$(echo "$ver" | cut -d. -f1)
            minor=$(echo "$ver" | cut -d. -f2)
            if [ "$major" -ge 3 ] && [ "$minor" -ge 9 ]; then
                echo "$c"
                return 0
            fi
        fi
    done
    return 1
}

check_python_venv() {
    local python_cmd="$1"
    # try creating a throwaway venv to confirm the module works
    local tmp_venv
    tmp_venv=$(mktemp -d)
    if $python_cmd -m venv "$tmp_venv" &>/dev/null; then
        rm -rf "$tmp_venv"
        return 0
    fi
    rm -rf "$tmp_venv"
    return 1
}

generate_secret() {
    if command -v python3 &>/dev/null; then
        python3 -c "import secrets; print(secrets.token_hex(32))"
    elif command -v openssl &>/dev/null; then
        openssl rand -hex 32
    else
        head -c 32 /dev/urandom | od -A n -t x1 | tr -d ' \n'
        echo ""
    fi
}

wait_for_health() {
    local url="$1" max_wait="${2:-30}"
    local i=0
    while [ "$i" -lt "$max_wait" ]; do
        if curl -sf "$url" &>/dev/null; then
            return 0
        fi
        sleep 1
        i=$((i + 1))
    done
    return 1
}

prompt_yn() {
    local question="$1" default="${2:-n}"
    local hint="[y/N]"
    [ "$default" = "y" ] && hint="[Y/n]"
    echo -ne "  ${question} ${DIM}${hint}${NC}: " >&2
    local ans
    read -r ans
    ans="${ans:-$default}"
    [[ "$ans" =~ ^[yY] ]]
}

prompt_value() {
    local question="$1" default="${2:-}"
    if [ -n "$default" ]; then
        echo -ne "  ${question} ${DIM}[${default}]${NC}: " >&2
    else
        echo -ne "  ${question}: " >&2
    fi
    local val
    read -r val
    echo "${val:-$default}"
}

# --- .env setup ---

write_env() {
    local env_file="$1" port="$2"

    local secret
    secret=$(generate_secret)

    cat > "$env_file" <<ENV
# Generated by install-server.sh on $(date -u +"%Y-%m-%d %H:%M:%S UTC")
OSGSC_SECRET_KEY=${secret}
OSGSC_PORT=${port}
OSGSC_MAX_SAVE_SIZE_MB=50
OSGSC_MAX_VERSIONS=5

# Optional: restrict CORS to specific origins (comma-separated)
# OSGSC_CORS_ORIGINS=https://my-domain.com,http://localhost:3000
ENV

    chmod 600 "$env_file"
}

# --- Docker install ---

install_docker() {
    local port="$1" compose_cmd="$2" overwrite_env="$3"

    if [ "$overwrite_env" = "true" ]; then
        write_env "${PROJECT_DIR}/.env" "$port"
        ok "Created .env with generated secret key"
    else
        ok "Keeping existing .env"
    fi

    info "Building and starting container..."
    cd "$PROJECT_DIR"
    $compose_cmd up -d --build

    echo ""
    info "Waiting for server to start..."
    if wait_for_health "http://localhost:${port}/api/health" 30; then
        ok "Server is running!"
    else
        warn "Server didn't respond within 30s. Check logs:"
        echo "      $compose_cmd logs"
    fi
}

# --- Systemd install ---

install_systemd() {
    local port="$1"
    local python_cmd="$2"
    local install_dir="$3"
    local data_dir="$4"
    local service_user="$5"
    local overwrite_env="$6"

    # write .env to project dir first, then copy to install dir if needed
    if [ "$overwrite_env" = "true" ]; then
        write_env "${PROJECT_DIR}/.env" "$port"
        ok "Created .env with generated secret key"
    else
        ok "Keeping existing .env"
    fi

    if [ "$install_dir" != "$PROJECT_DIR" ]; then
        info "Copying project files to ${install_dir}..."
        sudo mkdir -p "$install_dir"
        sudo cp -r "${PROJECT_DIR}/server" "${PROJECT_DIR}/web" "${PROJECT_DIR}/run_server.py" "${PROJECT_DIR}/.env" "$install_dir/"
    fi

    # create venv and install deps before chowning, since we're running as current user
    local venv_dir="${install_dir}/venv"
    info "Creating virtual environment at ${venv_dir}..."
    sudo $python_cmd -m venv "$venv_dir"
    sudo "${venv_dir}/bin/pip" install --quiet --upgrade pip
    sudo "${venv_dir}/bin/pip" install --quiet -r "${install_dir}/server/requirements.txt"
    ok "Dependencies installed"

    # create data dirs, then chown everything to service user
    sudo mkdir -p "${data_dir}/saves" "${data_dir}/db"
    sudo chown -R "${service_user}:${service_user}" "$install_dir" "$data_dir"

    local unit_file="/etc/systemd/system/osgsc.service"
    info "Creating systemd service..."

    sudo tee "$unit_file" > /dev/null <<UNIT
[Unit]
Description=OSGSameCloudService — RetroArch cloud save server
After=network.target
Wants=network-online.target

[Service]
Type=simple
User=${service_user}
Group=${service_user}
WorkingDirectory=${install_dir}
EnvironmentFile=${install_dir}/.env
Environment=OSGSC_DATA_DIR=${data_dir}
ExecStart=${venv_dir}/bin/python run_server.py
Restart=on-failure
RestartSec=5

# hardening
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths=${data_dir}
PrivateTmp=true

[Install]
WantedBy=multi-user.target
UNIT

    ok "Created ${unit_file}"

    sudo systemctl daemon-reload
    sudo systemctl enable osgsc.service
    sudo systemctl start osgsc.service

    echo ""
    info "Waiting for server to start..."
    if wait_for_health "http://localhost:${port}/api/health" 15; then
        ok "Server is running!"
    else
        warn "Server didn't respond within 15s. Check status:"
        echo "      sudo systemctl status osgsc"
        echo "      sudo journalctl -u osgsc -n 50 --no-pager"
    fi
}

# --- Uninstall ---

do_uninstall() {
    echo ""
    echo -e "  ${BOLD}Uninstall OSGSameCloudService${NC}"
    echo ""

    if [ -f "${PROJECT_DIR}/docker-compose.yml" ]; then
        local compose_cmd=""
        if docker compose version &>/dev/null 2>&1; then
            compose_cmd="docker compose"
        elif command -v docker-compose &>/dev/null; then
            compose_cmd="docker-compose"
        fi
        if [ -n "$compose_cmd" ]; then
            info "Stopping Docker container..."
            cd "$PROJECT_DIR"
            $compose_cmd down 2>/dev/null || true
        fi
    fi

    if [ -f /etc/systemd/system/osgsc.service ]; then
        info "Stopping systemd service..."
        sudo systemctl stop osgsc.service 2>/dev/null || true
        sudo systemctl disable osgsc.service 2>/dev/null || true
        sudo rm -f /etc/systemd/system/osgsc.service
        sudo systemctl daemon-reload
        ok "Systemd service removed"
    fi

    echo ""
    warn "Data directories were NOT removed."
    echo "      To remove saves and database manually:"
    echo "        docker volume rm osgsc-data          # if using Docker"
    echo "        sudo rm -rf /opt/osgsc/data           # if using systemd"
    echo ""
    ok "Uninstall complete."
}

# --- Firewall ---

setup_firewall() {
    local port="$1"

    if command -v ufw &>/dev/null; then
        local status
        status=$(sudo ufw status 2>/dev/null | head -1) || return
        if echo "$status" | grep -qi "active"; then
            echo ""
            if prompt_yn "UFW firewall is active. Allow port ${port}/tcp?" "y"; then
                sudo ufw allow "${port}/tcp" comment "OSGSC save server"
                ok "Firewall rule added for port ${port}"
            fi
        fi
    elif command -v firewall-cmd &>/dev/null; then
        echo ""
        if prompt_yn "Open port ${port}/tcp in firewalld?" "y"; then
            sudo firewall-cmd --permanent --add-port="${port}/tcp"
            sudo firewall-cmd --reload
            ok "Firewall rule added for port ${port}"
        fi
    fi
}

# --- Main ---

main() {
    echo ""
    echo "  ================================================"
    echo "    OSGSameCloudService — Server Installer"
    echo "    Cloud saves for RetroArch"
    echo "  ================================================"

    # --help
    if [ "${1:-}" = "--help" ] || [ "${1:-}" = "-h" ]; then
        echo ""
        echo "  Usage:"
        echo "    bash install-server.sh            # install"
        echo "    bash install-server.sh --uninstall # remove"
        echo ""
        exit 0
    fi

    # --uninstall
    if [ "${1:-}" = "--uninstall" ] || [ "${1:-}" = "uninstall" ]; then
        do_uninstall
        exit 0
    fi

    # ==================================================================
    #  Step 1: Prerequisites
    # ==================================================================
    step_header "1" "Checking prerequisites"

    local has_docker=false has_python=false python_cmd="" python_ver=""
    local compose_cmd=""

    if command -v docker &>/dev/null; then
        has_docker=true
        ok "Docker found"
        # also check compose
        if docker compose version &>/dev/null; then
            compose_cmd="docker compose"
        elif command -v docker-compose &>/dev/null; then
            compose_cmd="docker-compose"
        fi
        if [ -n "$compose_cmd" ]; then
            ok "Docker Compose found"
        else
            warn "Docker Compose not found — Docker method unavailable"
            has_docker=false
        fi
    else
        info "Docker not found"
    fi

    if python_cmd=$(check_python); then
        has_python=true
        python_ver=$($python_cmd -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')")
        ok "Python ${python_ver} found (${python_cmd})"
        # check venv module
        if ! check_python_venv "$python_cmd"; then
            warn "python3-venv not installed — systemd method unavailable"
            warn "Fix with: sudo apt install python3-venv"
            has_python=false
        fi
    else
        info "Python 3.9+ not found"
    fi

    if [ "$has_docker" = false ] && [ "$has_python" = false ]; then
        echo ""
        err "No viable install method found. Install one of:"
        echo ""
        echo "      Docker (recommended):"
        echo "        curl -fsSL https://get.docker.com | sh"
        echo ""
        echo "      Python 3.9+ with venv:"
        echo "        sudo apt install python3 python3-pip python3-venv"
        echo ""
        exit 1
    fi

    # ==================================================================
    #  Step 2: Install method
    # ==================================================================
    step_header "2" "Install method"

    local method=""
    if [ "$has_docker" = true ] && [ "$has_python" = true ]; then
        echo ""
        echo "      1) Docker       — isolated container, easy updates"
        echo "      2) Systemd      — bare-metal service with Python venv"
        echo ""

        local choice=""
        while true; do
            choice=$(prompt_value "Choose [1 or 2]" "")
            case "$choice" in
                1) method="docker"; break;;
                2) method="systemd"; break;;
                *) echo -e "  ${RED}Please enter 1 or 2.${NC}" >&2;;
            esac
        done
    elif [ "$has_docker" = true ]; then
        method="docker"
        info "Only Docker is available — using Docker."
    else
        method="systemd"
        info "Only Python is available — using systemd service."
    fi

    # ==================================================================
    #  Step 3: Configuration
    # ==================================================================
    step_header "3" "Configuration"
    echo ""

    local port
    port=$(prompt_value "Server port" "4444")

    # systemd-specific settings
    local install_dir="" data_dir="" service_user=""
    if [ "$method" = "systemd" ]; then
        install_dir=$(prompt_value "Install directory" "/opt/osgsc")
        data_dir=$(prompt_value "Data directory (saves + database)" "${install_dir}/data")
        service_user=$(prompt_value "Run as user" "$USER")
    fi

    # handle existing .env now, not during install
    local overwrite_env="true"
    local env_file="${PROJECT_DIR}/.env"
    if [ -f "$env_file" ]; then
        local existing_key
        existing_key=$(grep "^OSGSC_SECRET_KEY=" "$env_file" | cut -d= -f2- || true)
        if [ -n "$existing_key" ]; then
            echo ""
            warn "Existing .env found with a secret key already set."
            if prompt_yn "Overwrite it? (all existing login tokens will be invalidated)" "n"; then
                overwrite_env="true"
            else
                overwrite_env="false"
            fi
        fi
    fi

    # handle existing install dir now, not during install
    local dir_confirmed="false"
    if [ "$method" = "systemd" ] && [ "$install_dir" != "$PROJECT_DIR" ] && [ -d "$install_dir" ]; then
        echo ""
        warn "Directory ${install_dir} already exists."
        if ! prompt_yn "Overwrite its contents?" "n"; then
            err "Aborted."
            exit 1
        fi
        dir_confirmed="true"
    fi

    # ==================================================================
    #  Step 4: Confirm
    # ==================================================================
    step_header "4" "Confirm"
    echo ""

    local server_ip
    server_ip=$(hostname -I 2>/dev/null | awk '{print $1}') || server_ip="<your-server-ip>"

    echo -e "      Method:       ${BOLD}${method}${NC}"
    echo -e "      Port:         ${BOLD}${port}${NC}"
    echo -e "      Server URL:   ${BOLD}http://${server_ip}:${port}${NC}"
    if [ "$method" = "systemd" ]; then
        echo -e "      Install dir:  ${BOLD}${install_dir}${NC}"
        echo -e "      Data dir:     ${BOLD}${data_dir}${NC}"
        echo -e "      Service user: ${BOLD}${service_user}${NC}"
    fi
    if [ "$overwrite_env" = "false" ]; then
        echo -e "      .env:         ${DIM}keep existing${NC}"
    else
        echo -e "      .env:         ${DIM}generate new secret key${NC}"
    fi
    echo ""

    if ! prompt_yn "Proceed with installation?" "y"; then
        echo ""
        info "Aborted."
        exit 0
    fi

    # ==================================================================
    #  Step 5: Installing
    # ==================================================================
    step_header "5" "Installing"

    case "$method" in
        docker)  install_docker "$port" "$compose_cmd" "$overwrite_env";;
        systemd) install_systemd "$port" "$python_cmd" "$install_dir" "$data_dir" "$service_user" "$overwrite_env";;
    esac

    # firewall
    setup_firewall "$port"

    # ==================================================================
    #  Done
    # ==================================================================
    echo ""
    echo "  ================================================"
    ok "Installation complete!"
    echo ""
    echo "      Server URL:  http://${server_ip}:${port}"
    echo "      Web UI:      http://${server_ip}:${port}"
    echo "      API docs:    http://${server_ip}:${port}/docs"
    echo "      Health:      http://${server_ip}:${port}/api/health"
    echo ""

    if [ "$method" = "docker" ]; then
        echo "      Manage:"
        echo "        docker compose logs -f          # view logs"
        echo "        docker compose restart           # restart"
        echo "        docker compose down              # stop"
        echo "        docker compose up -d --build     # rebuild after git pull"
    else
        echo "      Manage:"
        echo "        sudo systemctl status osgsc      # check status"
        echo "        sudo journalctl -u osgsc -f      # view logs"
        echo "        sudo systemctl restart osgsc     # restart"
        echo "        sudo systemctl stop osgsc        # stop"
    fi
    echo ""
    echo "      Uninstall:"
    echo "        bash ${PROJECT_DIR}/install-server.sh --uninstall"
    echo ""
    echo "      Next: set up your devices — see README.md section 3"
    echo "  ================================================"
    echo ""
}

main "$@"
